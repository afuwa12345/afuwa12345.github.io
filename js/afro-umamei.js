  var MAX = 9;   /* カタカナ9文字まで */
  var MIN = 2;

  /* ふつうの乱数だと同じ組がつづくので、混ぜてから使う */
  function mix(h) {
    h ^= h >>> 16; h = (h * 0x7feb352d) >>> 0;
    h ^= h >>> 15; h = (h * 0x846ca68b) >>> 0;
    h ^= h >>> 16;
    return h >>> 0;
  }
  function hash(str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = (h * 16777619) >>> 0;
    }
    return mix(h);
  }

  /* 種から、決まった名前を作る。同じ種なら必ず同じ名前になる */
  function make(seed) {
    var h = mix(seed >>> 0);
    var withKan = (h % 100) < 22;           /* 2割ちょっとは冠名つき */

    for (var tries = 0; tries < 60; tries++) {
      var a = HEAD[mix(h + tries * 7919) % HEAD.length];
      var b = TAIL[mix(h + tries * 104729 + 13) % TAIL.length];
      if (a.n === b.n) continue;

      var parts = [a, b];
      if (withKan) {
        var k = KAN[mix(h + tries * 31337 + 7) % KAN.length];
        if (k.n !== a.n && k.n !== b.n) parts = [k, a, b];
      }

      var name = parts.map(function (x) { return x.n; }).join('');
      if (name.length < MIN || name.length > MAX) continue;

      var why = parts.map(function (x) { return x.j; }).join('＋');
      return { name: name, why: why, kan: parts.length === 3 ? parts[0].n : '' };
    }
    /* どうしても収まらなかったときの逃げ道 */
    return { name: 'アフロホース', why: 'アフロ＋馬', kan: '' };
  }

